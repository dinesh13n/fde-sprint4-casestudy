#!/usr/bin/env python3
"""Load the ontology (+ synthetic instances) with rdflib, run the demo SPARQL queries, write sparql_results.md."""
import sys, json
from pathlib import Path
from rdflib import Graph
H = Path(__file__).resolve().parent.parent
g = Graph(); g.parse(H/"gxp-ontology.ttl"); g.parse(H/"gxp-instances.ttl")
P = """PREFIX gx: <https://example.org/gxp-hub/onto#> PREFIX skos: <http://www.w3.org/2004/02/skos/core#>
PREFIX rdfs: <http://www.w3.org/2000/01/rdf-schema#> PREFIX owl: <http://www.w3.org/2002/07/owl#> PREFIX rdf: <http://www.w3.org/1999/02/22-rdf-syntax-ns#>
"""
Q = [
("Q1 Entity classes per category", "Which kinds of things exist in the hub, grouped?",
 "SELECT ?category (COUNT(?c) AS ?classes) WHERE { ?c gx:category ?category } GROUP BY ?category ORDER BY DESC(?classes)"),
("Q2 Cases per status (instance data + SKOS label)", "Baseline status mix; labels come from the vocabulary, not from the row.",
 "SELECT ?status (COUNT(?x) AS ?cases) WHERE { ?x a gx:Case ; gx:Case_status ?s . ?s skos:prefLabel ?status } GROUP BY ?status ORDER BY DESC(?cases)"),
("Q3 Trace a CAPA to its material", "CAPA -> Deviation -> Batch -> Material through the four legacy foreign keys (REL-04, REL-03, REL-01).",
 "SELECT ?capa ?dev ?batch ?mat ?name WHERE { ?c a gx:CAPA ; rdfs:label ?capa ; gx:REL_04 ?d . ?d rdfs:label ?dev ; gx:REL_03 ?b . ?b rdfs:label ?batch ; gx:REL_01 ?m . ?m rdfs:label ?mat ; gx:Material_material_name ?name } ORDER BY ?capa LIMIT 8"),
("Q4 Which relationships have no enforcement in the legacy estate?", "Where the model has meaning but the legacy system has no key.",
 "SELECT ?rel ?from ?to WHERE { ?p a owl:ObjectProperty ; gx:enforcement 'none_in_legacy' ; rdfs:label ?rel ; rdfs:domain ?f ; rdfs:range ?t . ?f rdfs:label ?from . ?t rdfs:label ?to } ORDER BY ?from"),
("Q5 Gap proof: Cases linked to any quality object", "Expected 0. Case-to-batch/deviation/CAPA links cannot be derived (GAP-REL-2); they are human decisions.",
 "SELECT (COUNT(*) AS ?links) WHERE { ?c a gx:Case . ?c ?p ?o . ?o a ?t . VALUES ?t { gx:Batch gx:Deviation gx:CAPA } }"),
("Q6 Which vocabularies use the label CLOSED?", "Same word, different meanings; no mapping is asserted (ZH-05).",
 "SELECT ?vocab ?note WHERE { ?c skos:prefLabel 'CLOSED' ; skos:inScheme ?s . ?s skos:prefLabel ?vocab . OPTIONAL { ?c skos:note ?note } } ORDER BY ?vocab"),
("Q7 Any exact-match between concepts?", "Expected false: the ontology never equates statuses across vocabularies.",
 "ASK { ?a skos:exactMatch|skos:closeMatch|owl:sameAs ?b }"),
("Q8 Zone H: human-only actions and holders", "Ten actions, all requiring a named human; holder count shows who can act today.",
 "SELECT ?action ?holders WHERE { ?z a gx:ZoneHAction ; rdfs:label ?action ; gx:holderCount ?holders } ORDER BY ?action"),
("Q9 Metrics that cannot be computed today", "Honest measurement gaps, with their definition class.",
 "SELECT ?metric ?class WHERE { ?m a gx:MetricDefinition ; rdfs:label ?metric ; gx:computableToday false ; gx:definitionClass ?class } ORDER BY ?metric LIMIT 12"),
("Q10 MUST-rules that apply to Case", "Business rules bound to the Case class.",
 "SELECT ?rule ?text WHERE { ?r a gx:BusinessRule ; rdfs:label ?rule ; gx:strength 'MUST' ; gx:appliesTo gx:Case ; rdfs:comment ?text } ORDER BY ?rule LIMIT 8"),
("Q11 Personal-data / restricted classes", "Classes by sensitivity.",
 "SELECT ?class ?sens WHERE { ?c gx:sensitivity ?sens ; rdfs:label ?class } ORDER BY ?sens ?class"),
]
out = ["# SPARQL demo results", "", "Generated by `tools/run_sparql_demo.py` over `gxp-ontology.ttl` + `gxp-instances.ttl` (synthetic). rdflib. Triples loaded: %d." % len(g), ""]
res = []
for t, why, q in Q:
    r = g.query(P + q)
    out += ["## " + t, "", why, "", "```sparql", q, "```", ""]
    if r.type == "ASK":
        out += ["Result: **%s**" % bool(r.askAnswer), ""]; res.append((t, bool(r.askAnswer))); continue
    rows = [[str(x)[:110] if x is not None else "" for x in row] for row in r]
    hdr = [str(v) for v in r.vars]
    out += ["| " + " | ".join(hdr) + " |", "|" + "---|" * len(hdr)] + ["| " + " | ".join(x.replace("|", "/") for x in row) + " |" for row in rows] + ["", "%d row(s)." % len(rows), ""]
    res.append((t, len(rows)))
(H/"sparql_results.md").write_text("\n".join(out), encoding="utf-8")
for t, n in res: print(t, "->", n)
