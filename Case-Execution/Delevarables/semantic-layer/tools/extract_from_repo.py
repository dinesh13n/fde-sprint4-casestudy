#!/usr/bin/env python3
"""Generate static YAML from repo sources: spec-business-rules, access-permission-matrix, error-catalogue.
Usage: python3 tools/extract_from_repo.py [REPO_ROOT]   (default: env GXP_REPO or ../../../gxp-quality-hub-legacy)"""
import json, os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.dirname(HERE)
REPO = sys.argv[1] if len(sys.argv) > 1 else os.environ.get("GXP_REPO") or os.path.normpath(os.path.join(OUT, "..", "..", "gxp-quality-hub-legacy"))

def q(s):
    return json.dumps(s, ensure_ascii=False)

def sbr():
    p = "docs/12-specs/business-rules.md"
    rows = []
    for line in open(os.path.join(REPO, p), encoding="utf-8"):
        m = re.match(r"\|\s*(SBR-[A-Z]+-\d+)\s*(\*\*\[PARAM\]\*\*)?\s*\|(.*)\|([^|]*)\|\s*$", line)
        if m:
            rows.append((m.group(1), bool(m.group(2)), m.group(3).strip(), m.group(4).strip()))
    with open(os.path.join(OUT, "spec-business-rules.yaml"), "w", encoding="utf-8") as f:
        f.write("# GENERATED by tools/extract_from_repo.py from %s. Do not edit.\n" % p)
        f.write('semantic_layer_version: "0.1.0"\nkind: spec-business-rules\nsource: %s\nitems:\n' % p)
        for rid, param, stmt, impl in rows:
            f.write("  - {id: %s, param: %s, statement: %s, implements: %s, epistemic_status: verified_fact, evidence: [%s]}\n"
                    % (rid, str(param).lower(), q(stmt), q(impl), p))
    return len(rows)

def perms():
    p = "hub/security/route_registry.json"
    d = json.load(open(os.path.join(REPO, p), encoding="utf-8"))
    with open(os.path.join(OUT, "access-permission-matrix.yaml"), "w", encoding="utf-8") as f:
        f.write("# GENERATED by tools/extract_from_repo.py from %s. Do not edit.\n" % p)
        f.write('semantic_layer_version: "0.1.0"\nkind: access-permission-matrix\ndefault: deny\nsource: %s\nroutes:\n' % p)
        for r in d["routes"]:
            f.write("  - {method: %s, path: %s, op_id: %s, roles: %s}\n" % (r["method"], q(r["path"]), r["op_id"], json.dumps(r["roles"])))
    return len(d["routes"])

def errors():
    p = "docs/27-hardening/error-registry/error-code-registry.json"
    d = json.load(open(os.path.join(REPO, p), encoding="utf-8"))
    with open(os.path.join(OUT, "error-catalogue.yaml"), "w", encoding="utf-8") as f:
        f.write("# GENERATED by tools/extract_from_repo.py from %s. Do not edit.\n" % p)
        f.write('semantic_layer_version: "0.1.0"\nkind: error-catalogue\nsource: %s\nitems:\n' % p)
        for c in d["codes"]:
            f.write("  - {code: %s, area: %s, http: %s, exit_code: %s, in_stage12_spec: %s}\n"
                    % (c["code"], c["area"], c.get("http"), c.get("exit_code"), str(bool(c.get("in_stage12_spec"))).lower()))
    return len(d["codes"])

if __name__ == "__main__":
    print("repo:", REPO)
    print("SBR rules:", sbr(), "| routes:", perms(), "| error codes:", errors())
